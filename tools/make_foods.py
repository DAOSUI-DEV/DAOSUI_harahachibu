def num(v):
    if v is None: return None
    s = str(v).strip()
    if s in ('', '-', '*', '…'): return None
    if 'Tr' in s: return 0.0
    s = s.strip('()（）')
    try: return float(s)
    except ValueError: return None

def clean(name):
    s = re.sub(r'\s+', ' ', name.replace('　', ' ')).strip()
    s = re.sub(r'＜[^＞]*＞\s*', '', s)
    s = re.sub(r'^（[^）]*類）\s*', '', s)
    s = s.replace('・主品目', '').replace('・副品目', '').replace('［二次品目］ ', '')
    s = s.replace('［', '').replace('］', '')
    return s

def main(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    rows = list(wb['表全体'].iter_rows(values_only=True))
    ids = rows[11]
    col = {k: i for i, k in enumerate(ids) if k}
    out = []
    for r in rows[12:]:
        if not r[1]: continue
        no = str(r[1]).zfill(5)
        raw = str(r[3])
        name = clean(raw)
        g = int(str(r[0]))
        kcal = num(r[col['ENERC_KCAL']])
        p = num(r[col['PROT-']])
        p = p if p is not None else num(r[col['PROTCAA']])
        f = num(r[col['FAT-']])
        f = f if f is not None else num(r[col['FATNLEA']])
        c = num(r[col['CHOCDF-']])
        fib = num(r[col['FIB-']])
        salt = num(r[col['NACL_EQ']])
        refuse = num(r[col['REFUSE']]) or 0
        nice, units = COMMON.get(no, (None, None))
        syn = ' '.join(v for k, v in SYN if k in raw)
        rnd = lambda x: None if x is None else round(x, 1)
        out.append([no, name, nice, g, int(round(kcal or 0)), rnd(p), rnd(f), rnd(c), rnd(fib), rnd(salt), int(refuse), units, syn])
    missing = [k for k in COMMON if k not in {o[0] for o in out}]
    assert not missing, missing
    data = {'v': '日本食品標準成分表（八訂）増補2023年', 'cite': '日本食品標準成分表（八訂）増補2023年から引用', 'groups': GROUPS,
            'cols': ['番号', '食品名', 'よく使う名前', '食品群', 'kcal', 'たんぱく質', '脂質', '炭水化物', '食物繊維', '食塩相当量', '廃棄率%', 'よく使う量', '別名'],
            'foods': out}
    dst = ROOT / 'data' / 'foods.json'
    dst.write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    print('foods', len(out), 'common', len(COMMON), 'bytes', dst.stat().st_size)

if __name__ == '__main__':
    main(sys.argv[1])
