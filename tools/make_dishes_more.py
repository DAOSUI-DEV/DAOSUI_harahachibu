"""料理の目安（追加分）を作る → data/dishes-more.json
- 「成分表から計算」：寿司・刺身・焼き鳥・おでん・天ぷら・おにぎり・果物は、日本食品標準成分表（八訂）増補2023年の値 × 材料の量で計算
- それ以外は一般的な1人前の目安（概算）。お店や作り方で変わる
使い方: python3 tools/make_dishes_more.py
行の形は dishes.js と同じ：[名前, kcal, たんぱく質, 脂質, 炭水化物, 食塩相当量, 単位, 分類, 読み・別名, 役割]
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FOODS = {r[0]: r for r in json.load(open(ROOT / 'data/foods.json'))['foods']}
ROWS, NAMES = [], set()

def per(code):
    USED.add(code)
    r = FOODS[code]
    z = lambda v: v or 0
    return r[4], z(r[5]), z(r[6]), z(r[7]), z(r[9])

def calc(parts):
    k = p = f = c = s = 0.0
    for code, g in parts:
        kk, pp, ff, cc, ss = per(code)
        k += kk * g / 100; p += pp * g / 100; f += ff * g / 100; c += cc * g / 100; s += ss * g / 100
    return round(k), round(p, 1), round(f, 1), round(c, 1), round(s, 1)

import re as _re
BASE = set(_re.findall(r"^\s*\['([^']+)',", (ROOT / 'data/dishes.js').read_text(encoding='utf-8'), _re.M))
USED = set()

def add(name, k, p, f, c, s, unit, group, y='', role='x'):
    if name in NAMES or name in BASE: sys.exit('名前が重複: ' + name)
    NAMES.add(name)
    ROWS.append([name, k, p, f, c, s, unit, group, y, role])

def M(name, unit, group, y, parts):
    add(name, *calc(parts), unit, group, y + ' 成分表から計算')

def E(group, rows, skip_base=False):
    for r in rows:
        name, k, p, f, c, s, unit = r[:7]
        if skip_base and name in BASE: continue      # dishes.js にすでにある物（かけうどん など）
        y = r[7] if len(r) > 7 else ''
        add(name, k, p, f, c, s, unit, group, y)

